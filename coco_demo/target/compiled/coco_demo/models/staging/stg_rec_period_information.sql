WITH source AS (
    SELECT * FROM COCO_LIVE_DB.CUSTOMER_A_DATA.rec_period_information
    WHERE DELETE_FLAG = FALSE OR DELETE_FLAG IS NULL
)

SELECT
    PKID AS period_info_id,
    ASSIGNMENT_ID,
    PERIOD_ID,
    CONSOLIDATION_ID,
    FINANCIAL_STATEMENT_ID,
    ACTIVE_STATUS AS is_active,
    ACTIVITY_IN_PERIOD AS has_activity,
    KEY_ACCOUNT AS is_key_account,
    PURPOSE,
    RECONCILIATION_PROCEDURE,
    RECON_FREQUENCY,
    BALANCE_GL,
    BALANCE_GL_BASE,
    BALANCE_GL_FUNC,
    BALANCE_BANK,
    BALANCE_BANK_BASE,
    BALANCE_BANK_FUNC,
    BALANCE_SUBLEDGER,
    BALANCE_SUBLEDGER_BASE,
    BALANCE_SUBLEDGER_FUNC,
    BALANCE_ESTIMATE,
    BALANCE_ESTIMATE_BASE,
    BALANCE_ESTIMATE_FUNC,
    BALANCE_FORECAST,
    BALANCE_FORECAST_BASE,
    BALANCE_FORECAST_FUNC,
    ACCOUNT_BALANCE_LAST_UPDATE_DATE,
    LAST_UPDATE_DATE,
    DB_INSERT_DATE AS created_at,
    DB_UPDATE_DATE AS updated_at
FROM source